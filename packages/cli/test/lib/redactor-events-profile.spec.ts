// The "events" profile: the SEVEN required tests (ruling §7).
//
// What the profile is. Same literal credential patterns as "full", same entropy
// bar as "full" (2 character classes, 3.5 bits), plus ONE exemption: a
// path-shaped token (contains a slash, contains lowercase, contains NO
// uppercase) is not eaten by the entropy sweep. Exactly one production caller,
// `mla _internal redact-events`, the flush-time boundary for the hook spool.
//
// Why it is a third profile and not a loosening of "full". "full" is three
// things at once: the at-rest default, the block-on-detect scanner's bar, and
// the fallback for an unrecognized profile name. Relaxing it would relax all
// three, silently, for callers that never asked. Test 3 and test 4 are the ones
// that prove that did not happen.
//
// The measurement these tests are built on lives in
// test/fixtures/redaction-path-corpus.json, regenerated by
// scripts/measure-redaction-corpus.js against a real transcript corpus. It is
// frozen deliberately: the live corpus grows every session, so a test that
// re-measured would never be deterministic.

interface PathCorpus {
  transcripts: number;
  distinctTokens: number;
  totalOccurrences: number;
  tokens: Record<string, number>;
}

const CORPUS: PathCorpus = JSON.parse(
  readFileSync(join(__dirname, "..", "fixtures", "redaction-path-corpus.json"), "utf8"),
);

